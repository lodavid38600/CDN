/** Retourne le code de section (chiffres romains) d'un chapitre "01".."97". */
export function sectionOfChapter(chapter) {
  const n = Number(chapter);
  const s = SECTIONS.find((sec) => n >= sec.chapters[0] && n <= sec.chapters[1]);
  return s ? s.code : null;
}

/** Arborescence sections -> chapitres, prête à être servie au client. */
export function nomenclatureTree() {
  return SECTIONS.map((s) => ({
    code: s.code,
    label: s.label,
    chapters: Object.entries(CHAPTERS)
      .filter(([c]) => Number(c) >= s.chapters[0] && Number(c) <= s.chapters[1])
      .map(([code, label]) => ({ code, label })),
  }));
}
